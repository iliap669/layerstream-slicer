"""G-code layer splitting and (when installed) CuraEngine / PrusaSlicer slicing."""

from __future__ import annotations

from pathlib import Path

import pytest

from layerstream_slicer.slicing.engine import engine_available, find_engine, get_slicer
from layerstream_slicer.slicing.gcode_layers import extract_layer_paths, split_gcode_layers
from layerstream_slicer.slicing.interface import SlicerSettings
from layerstream_slicer.slicing.stub import StubSlicer
from tests.conftest import sitting_box

CURA_SAMPLE = """\
;FLAVOR:Marlin
;LAYER_COUNT:3
; LayerStream V3 KE start
G90
M82
G92 E0
;LAYER:0
G0 F3600 X10 Y10 Z0.2
G1 X20 Y10 E0.4
G1 X20 Y20 E0.8
;TIME_ELAPSED:1.0
;LAYER:1
G0 Z0.4
G1 X10 Y20 E1.2
G1 X10 Y10 E1.6
;TIME_ELAPSED:2.0
;LAYER:2
G0 Z0.6
G1 X20 Y10 E2.0
;TIME_ELAPSED:3.0
; LayerStream V3 KE end
G91
G1 E-2 F1800
G90
"""

PRUSA_SAMPLE = """\
; generated by PrusaSlicer
;LAYER_CHANGE
;Z:0.2
G1 X5 Y5 E0.1
;LAYER_CHANGE
;Z:0.4
G1 X6 Y6 E0.2
;LAYER_CHANGE
;Z:0.6
G1 X7 Y7 E0.3
"""


def test_split_cura_layers_is_one_based() -> None:
    split = split_gcode_layers(CURA_SAMPLE)
    assert split.layer_count_hint == 3
    assert [layer.index for layer in split.layers] == [1, 2, 3]
    assert split.layers[0].z == 0.2
    assert "G1 X20 Y10 E0.4" in split.layers[0].gcode
    assert ";LAYER:0" in split.layers[0].gcode
    assert "G1 X10 Y20 E1.2" in split.layers[1].gcode
    assert "LayerStream V3 KE start" in split.preamble
    assert "LayerStream V3 KE end" in split.postamble
    source = split.source_from(2)
    assert source.get_layer(1) is None
    assert source.get_layer(2) is not None
    assert source.get_layer(3) is not None
    assert source.layer_count() == 3


def test_split_prusaslicer_layer_change() -> None:
    split = split_gcode_layers(PRUSA_SAMPLE)
    assert [layer.index for layer in split.layers] == [1, 2, 3]
    assert split.layers[1].z == pytest.approx(0.4)
    assert "G1 X6 Y6 E0.2" in split.layers[1].gcode


def test_extract_layer_paths_tracks_travel_and_extrusion() -> None:
    paths = extract_layer_paths(
        "G90\nG0 X10 Y10\nG1 X20 Y10 E0.4\nG1 X20 Y20 E0.8\nG0 X0 Y0\nG1 X1 Y1 E1.0\n"
    )
    assert len(paths) >= 2
    first = paths[0]
    assert first[0] == [10.0, 10.0]
    assert [20.0, 20.0] in first or first[-1] == [20.0, 20.0]


def test_get_slicer_stub_fallback() -> None:
    slicer, name = get_slicer(prefer="stub")
    assert name == "stub"
    assert isinstance(slicer, StubSlicer)


@pytest.mark.skipif(not engine_available(), reason="CuraEngine / PrusaSlicer is not installed")
def test_engine_slices_box_into_marked_layers(tmp_path: Path) -> None:
    info = find_engine()
    assert info is not None
    mesh = sitting_box(20, 20, 4)
    stl = tmp_path / "box.stl"
    mesh.export(stl)

    slicer, name = get_slicer(prefer="auto")
    assert name != "stub"
    settings = SlicerSettings(layer_height=0.2, nozzle_diameter=0.4, line_width=0.42)
    split = slicer.slice_mesh(stl, settings)

    # 4 mm / 0.2 mm = 20 layers, allow a little slack for first-layer height.
    assert len(split.layers) >= 15
    assert split.layers[0].index == 1
    assert any(
        ";LAYER:" in split.layers[0].gcode or ";LAYER_CHANGE" in split.layers[0].gcode
        for _ in [0]
    )
    # Toolpaths should actually move in XY, not just comment stubs.
    paths = extract_layer_paths(split.layers[2].gcode)
    assert paths, "expected real XY moves in a middle layer"
    mid = split.get_layer(5)
    assert mid is not None
    assert mid.z > 0
    from_n = split.source_from(8)
    assert from_n.get_layer(7) is None
    assert from_n.get_layer(8) is not None
